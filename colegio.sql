DROP DATABASE IF EXISTS colegio_diferencial;
CREATE DATABASE IF NOT EXISTS colegio_diferencial;
use colegio_diferencial;

CREATE TABLE usuario(
	rut_usuario VARCHAR(10) PRIMARY KEY,
    nombre varchar(30) NOT NULL,
    email varchar(50) NOT NULL UNIQUE,
    contrasenia varchar(50) NOT NULL
    )ENGINE = INNODB;
CREATE TABLE profesor(
    rut_profesor VARCHAR(10) PRIMARY KEY,
    asignatura varchar(20) NOT NULL,
    FOREIGN KEY(rut_profesor) REFERENCES usuario(rut_usuario)
    )ENGINE=InnoDB;
CREATE TABLE apoderado(
    rut_apoderado VARCHAR(10) PRIMARY KEY,
    telefono varchar(9) NOT NULL,
    FOREIGN KEY(rut_apoderado) REFERENCES usuario(rut_usuario)
    )ENGINE=InnoDB;
CREATE TABLE mensaje(
    id_mensaje INT AUTO_INCREMENT PRIMARY KEY,
    contenido varchar(60) NOT NULL,
    rut_profesor VARCHAR(10),
    fecha DATE,
    FOREIGN KEY(rut_profesor) REFERENCES profesor(rut_profesor)
	)ENGINE=InnoDB;
CREATE TABLE mensaje_apoderado(
    id_mensaje INT,
    rut_apoderado VARCHAR(10),
    PRIMARY KEY(id_mensaje, rut_apoderado),
    FOREIGN KEY(id_mensaje) REFERENCES mensaje(id_mensaje),
    FOREIGN KEY(rut_apoderado) REFERENCES apoderado(rut_apoderado)
	)ENGINE=InnoDB;
CREATE TABLE curso(
    id_curso INT PRIMARY KEY,
    nivel VARCHAR(12),
    tamanio INT 
)ENGINE= InnoDB;
CREATE TABLE profesor_curso(
    rut_profesor VARCHAR(10),
    id_curso INT,
    profesor_jefe BOOLEAN,
    PRIMARY KEY(rut_profesor, id_curso),
    FOREIGN KEY(rut_profesor) REFERENCES profesor(rut_profesor),
    FOREIGN KEY(id_curso) REFERENCES curso(id_curso)
)ENGINE= InnoDB;
CREATE TABLE alumno(
    rut_alumno VARCHAR(10) PRIMARY KEY,
    nombre VARCHAR(30),
    id_curso int,
    FOREIGN KEY(id_curso) REFERENCES curso(id_curso)
)ENGINE= InnoDB;
CREATE TABLE alumno_apoderado(
    rut_apoderado VARCHAR(10),
    rut_alumno VARCHAR(10),
    parentesco VARCHAR(30),
    es_principal BOOLEAN,
    PRIMARY KEY(rut_apoderado,rut_alumno),
    FOREIGN KEY(rut_apoderado) REFERENCES apoderado(rut_apoderado),
    FOREIGN KEY(rut_alumno) REFERENCES alumno(rut_alumno)
)ENGINE = InnoDB;
CREATE TABLE observacion(
    id_observacion INT AUTO_INCREMENT PRIMARY KEY,
    rut_alumno VARCHAR(10),
    rut_profesor VARCHAR(10),
    contenido VARCHAR(50),
    FOREIGN KEY(rut_alumno) REFERENCES alumno(rut_alumno),
    FOREIGN KEY(rut_profesor) REFERENCES profesor(rut_profesor)
)ENGINE =InnoDB;


